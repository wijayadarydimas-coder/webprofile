export const ALL_PROVIDERS = Object.values(PROVIDER_REGISTRY);

export function getProviderMeta(providerId: string): ProviderMeta {
  const normalized = (providerId || "").toLowerCase().trim();
  if (PROVIDER_REGISTRY[normalized]) {
    return PROVIDER_REGISTRY[normalized];
  }
  // Fallback for custom or unrecognized providers
  return {
    id: normalized,
    name: providerId.charAt(0).toUpperCase() + providerId.slice(1),
    category: "Cloud & Deployment",
    placeholder: "https://...",
    badgeBg: "bg-[#171A24]",
    badgeText: "text-[#7790FF]",
    badgeBorder: "border-[#7790FF]/30",
    dotColor: "#7790FF",
  };
}
